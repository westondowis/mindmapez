#!/usr/bin/env node
/**
 * Regenerates src/lib/emoji-data.ts from the official Unicode emoji-test.txt.
 *
 *   curl -sO https://unicode.org/Public/emoji/latest/emoji-test.txt
 *   node scripts/gen-emoji-data.mjs emoji-test.txt
 *
 * Keeps fully-qualified emoji only, drops skin-tone variants and the Component
 * group, and caps at MAX_VERSION so every glyph renders on current iOS/Android.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const MAX_VERSION = 15.1;
const GROUP_IDS = {
  "Smileys & Emotion": "smileys",
  "People & Body": "people",
  "Animals & Nature": "animals",
  "Food & Drink": "food",
  Activities: "activities",
  "Travel & Places": "travel",
  Objects: "objects",
  Symbols: "symbols",
  Flags: "flags",
};

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/gen-emoji-data.mjs <emoji-test.txt>");
  process.exit(1);
}
const text = await readFile(src, "utf8");
const version = text.match(/^# Version: ([\d.]+)/m)?.[1] ?? "unknown";
const groups = Object.fromEntries(Object.values(GROUP_IDS).map((id) => [id, []]));
let group = null;
let subgroup = "";
let count = 0;
for (const line of text.split("\n")) {
  const g = line.match(/^# group: (.+)$/);
  if (g) {
    group = GROUP_IDS[g[1].trim()] ?? null;
    continue;
  }
  const s = line.match(/^# subgroup: (.+)$/);
  if (s) {
    subgroup = s[1].trim();
    continue;
  }
  if (!group || line.startsWith("#") || !line.includes("; fully-qualified")) continue;
  const m = line.match(/#\s+(\S+)\s+E([\d.]+)\s+(.+)$/);
  if (!m) continue;
  const [, emoji, ver, name] = m;
  if (Number(ver) > MAX_VERSION) continue;
  if (/skin tone/.test(name)) continue;
  if (/[|\n]/.test(name)) continue;
  groups[group].push(`${emoji}|${name.trim()}|${subgroup}`);
  count += 1;
}

const out = [
  "// Generated by scripts/gen-emoji-data.mjs from Unicode emoji-test.txt. Do not edit by hand.",
  `// Source version ${version}; fully-qualified, no skin-tone variants, emoji <= E${MAX_VERSION}. ${count} entries.`,
  "// Each group is newline-separated `emoji|cldr name|subgroup` rows (parsed in emoji-search.ts).",
  "",
  `export const EMOJI_SOURCE_VERSION = ${JSON.stringify(version)};`,
  "",
  "export const EMOJI_ROWS: Record<string, string> = {",
  ...Object.entries(groups).map(([id, rows]) => `  ${id}: ${JSON.stringify(rows.join("\n"))},`),
  "};",
  "",
].join("\n");
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "emoji-data.ts");
await writeFile(target, out);
console.log(`[emoji] wrote ${count} entries to ${target}`);
